function applyLanguage(lang) {
  const dict = I18N[lang] || I18N.tr;
  document.documentElement.lang = lang;
  document.title = lang === "en"
    ? "Beytarchiver — All-in-One File Toolkit for Windows"
    : "Beytarchiver — Windows için Hepsi Bir Arada Dosya Aracı";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const [attr, key] = el.getAttribute("data-i18n-attr").split(":");
    if (attr && dict[key]) el.setAttribute(attr, dict[key]);
  });

  const btn = document.getElementById("langToggle");
  if (btn) {
    btn.textContent = lang === "en" ? "TR" : "EN";
    btn.setAttribute("aria-label", lang === "en" ? "Türkçe'ye geç" : "Switch to English");
  }
}

document.addEventListener("DOMContentLoaded", () => {
  let currentLang = document.documentElement.lang === "en" ? "en" : "tr";
  applyLanguage(currentLang);

  const langBtn = document.getElementById("langToggle");
  if (langBtn) {
    langBtn.addEventListener("click", () => {
      currentLang = currentLang === "tr" ? "en" : "tr";
      try { localStorage.setItem("beyt-lang", currentLang); } catch (e) {}
      applyLanguage(currentLang);
    });
  }

  // Lightbox modal dialog with mandatory light-dismiss fallback for browsers without closedBy
  const dialog = document.getElementById("lightbox");
  const dialogImg = document.getElementById("lightboxImg");

  if (dialog && dialogImg) {
    document.querySelectorAll(".shot").forEach((btn) => {
      btn.addEventListener("click", () => {
        const src = btn.getAttribute("data-full");
        const img = btn.querySelector("img");
        dialogImg.src = src || "";
        dialogImg.alt = img ? img.alt : "";
        dialog.showModal();
      });
    });

    if (!("closedBy" in HTMLDialogElement.prototype)) {
      dialog.addEventListener("click", (event) => {
        if (event.target !== dialog) return;
        const rect = dialog.getBoundingClientRect();
        const isDialogContent = (
          rect.top <= event.clientY &&
          event.clientY <= rect.top + rect.height &&
          rect.left <= event.clientX &&
          event.clientX <= rect.left + rect.width
        );
        if (isDialogContent) return;
        dialog.close();
      });
    }
  }

  // Live maintenance mode check (instant via GitHub raw API + local status.json fallback)
  const overlay = document.getElementById("maintenanceOverlay");
  const dismissBtn = document.getElementById("maintDismiss");
  let userDismissed = false;

  if (dismissBtn && overlay) {
    dismissBtn.addEventListener("click", () => {
      userDismissed = true;
      overlay.hidden = true;
    });
  }

  async function checkMaintenance() {
    if (!overlay) return;
    let data = null;
    try {
      const res = await fetch(
        "https://api.github.com/repos/Beytarchiver/beytarchiver.github.io/contents/status.json?t=" + Date.now(),
        { headers: { Accept: "application/vnd.github.raw+json" }, cache: "no-store" }
      );
      if (res.ok) data = await res.json();
    } catch (e) {}

    if (!data) {
      try {
        const res2 = await fetch("status.json?t=" + Date.now(), { cache: "no-store" });
        if (res2.ok) data = await res2.json();
      } catch (e) {}
    }

    if (data && typeof data.maintenance === "boolean") {
      if (!data.maintenance) {
        userDismissed = false;
        overlay.hidden = true;
      } else if (!userDismissed) {
        overlay.hidden = false;
      }
    }
  }

  checkMaintenance();
  setInterval(checkMaintenance, 15000);
});
